async function setup(t,{database=':memory:',now=()=>Date.now()}={}) {
  const app=createServer({database,now});app.server.listen(0,'127.0.0.1');await once(app.server,'listening');
  const origin=`http://127.0.0.1:${app.server.address().port}`;
  t.after(()=>new Promise(resolve=>app.server.close(resolve)));
  function player(){let cookie='';return async(path,body,extra={})=>{
    const res=await fetch(origin+'/api/'+path,{method:body===undefined?'GET':'POST',headers:{Cookie:cookie,...(body===undefined?{}:{Origin:origin,'Content-Type':'application/json'}),...extra},body:body===undefined?undefined:JSON.stringify(body)});
    if(res.headers.get('set-cookie'))cookie=res.headers.get('set-cookie').split(';')[0];
    return{status:res.status,data:await res.json(),headers:res.headers};
  };}
  return{...app,origin,player};
}
test('two players receive identical boards; server ignores claimed scores and rejects replay',async t=>{
  const {player}=await setup(t);const a=player(),b=player();await a('me');await b('me');
  const created=await a('rooms',{}),code=created.data.code;assert.match(code,/^[A-F0-9]{8}$/);
  const joined=await b(`rooms/${code}/join`,{});const ar=await a(`rooms/${code}`);assert.deepEqual(ar.data.state,joined.data.state);
  const s=ar.data.state,action={type:'place',slot:0,cell:s.cells.findIndex(c=>!c.stack.length&&!c.rock)};
  const move=await a(`rooms/${code}/action`,{seq:0,action,score:999999999});assert.equal(move.status,200);assert.notEqual(move.data.state.score,999999999);assert.equal(move.data.seq,1);
  assert.equal((await a(`rooms/${code}/action`,{seq:0,action})).status,409);
  assert.equal((await a(`rooms/${code}/action`,{seq:1,action:{type:'hammer',cell:0}})).status,400);
  const outsider=player();await outsider('me');assert.equal((await outsider(`rooms/${code}`)).status,403);
});
test('forfeit updates Elo once, persists ladder, and lets players create another room',async t=>{
  const {player}=await setup(t);const a=player(),b=player();const pa=(await a('me')).data,pb=(await b('me')).data;
  const code=(await a('rooms',{})).data.code;await b(`rooms/${code}/join`,{});
  const end=await a(`rooms/${code}/resign`,{});assert.equal(end.data.result.winner,pb.id);assert.equal(end.data.result.delta[pb.id],12);
  await a(`rooms/${code}/resign`,{});await b(`rooms/${code}`);
  assert.equal((await a('me')).data.rating,988);assert.equal((await b('me')).data.rating,1012);
  const ladder=(await a('ladder')).data.players;assert.equal(ladder[0].id,pb.id);assert.equal(ladder[1].id,pa.id);
  assert.equal((await a('rooms',{})).status,200);
});
test('timeout ends unfinished matches exactly once; waiting rooms expire',async t=>{
  let time=Date.UTC(2026,9,19,12);const {player,sweep}=await setup(t,{now:()=>time});const a=player(),b=player();await a('me');await b('me');
  const code=(await a('rooms',{})).data.code;await b(`rooms/${code}/join`,{});time+=600001;sweep();
  assert.equal((await a(`rooms/${code}`)).data.status,'finished');assert.equal((await a('me')).data.draws,1);sweep();assert.equal((await a('me')).data.draws,1);
  const waiting=(await a('rooms',{})).data.code;time+=600001;sweep();assert.equal((await a(`rooms/${waiting}`)).data.status,'cancelled');
});
test('daily UTC rollover rejects old run; refresh does not grant an extra attempt',async t=>{
  let time=Date.UTC(2026,9,19,23,59);const {player}=await setup(t,{now:()=>time});const a=player();await a('me');
  const first=(await a('daily',{})).data,again=(await a('daily',{})).data;assert.equal(first.id,again.id);assert.deepEqual(first.state,again.state);
  const action={type:'place',slot:0,cell:first.state.cells.findIndex(c=>!c.stack.length&&!c.rock)};
  time+=120000;assert.equal((await a('daily/action',{id:first.id,seq:0,action})).status,409);
  const next=(await a('daily',{})).data;assert.notEqual(first.id,next.id);assert.equal(next.state.day,'2026-10-20');
});
test('daily finished scores are generated by engine, not request payload',async t=>{
  const {player}=await setup(t);const a=player();await a('me');let run=(await a('daily',{})).data;
  for(let i=0;i<25&&run.state.status==='playing';i++){
    const action={type:'place',slot:run.state.dock.findIndex(Boolean),cell:run.state.cells.findIndex(c=>!c.stack.length&&!c.rock)};
    const r=await a('daily/action',{id:run.id,seq:run.seq,action,score:99999999});assert.equal(r.status,200);run=r.data;
  }
  assert.notEqual(run.state.status,'playing');const ladder=(await a('ladder')).data;assert.equal(ladder.daily[0].score,run.state.score);assert.notEqual(ladder.daily[0].score,99999999);
  assert.equal((await a('daily',{})).data.state.status,run.state.status);
});
test('HTTP security: CSRF rejected, HTML nicknames rejected, private source not served',async t=>{
  const {player,origin}=await setup(t);const a=player();const me=await a('me');assert.match(me.headers.get('set-cookie'),/HttpOnly/);assert.match(me.headers.get('set-cookie'),/SameSite=Strict/);
  assert.equal((await a('rooms',{}, {Origin:'https://attacker.invalid'})).status,403);
  assert.equal((await a('profile',{name:'<img src=x>'})).status,400);
  const res=await fetch(origin+'/server/main.mjs');assert.equal(res.status,404);assert.match(res.headers.get('content-security-policy'),/frame-ancestors 'none'/);
});
test('SQLite data survives server restart',async t=>{
  const dir=mkdtempSync(join(tmpdir(),'hexa-test-'));t.after(()=>rmSync(dir,{recursive:true,force:true}));
  const database=join(dir,'arena.sqlite');const first=createServer({database});first.server.listen(0,'127.0.0.1');await once(first.server,'listening');
  first.db.prepare('INSERT INTO players(id,name,rating,wins) VALUES(?,?,?,?)').run('persist','Persistant',1234,1);
  await new Promise(resolve=>first.server.close(resolve));
  const second=await setup(t,{database});assert.equal(second.db.prepare('SELECT rating FROM players WHERE id=?').get('persist').rating,1234);
});
